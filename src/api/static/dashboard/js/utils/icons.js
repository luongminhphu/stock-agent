/**
 * Trả về chuỗi SVG inline. Kế thừa currentColor; kích thước mặc định 16px
 * (dense table). Dùng 20px cho toolbar, 24px cho nav.
 *
 * @param {keyof PATHS} name
 * @param {{ size?: number, cls?: string, label?: string }} [opts]
 *   label: nếu có → role="img" + aria-label; nếu không → aria-hidden.
 */
export function icon(name, opts = {}) {
  const body = PATHS[name];
  if (!body) return '';
  const size = opts.size ?? 16;
  const cls  = opts.cls ? ` ${opts.cls}` : '';
  const a11y = opts.label
    ? `role="img" aria-label="${opts.label}"`
    : 'aria-hidden="true"';
  return `<svg class="ic${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`;
}

